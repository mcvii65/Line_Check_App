import plotly.graph_objects as go
import streamlit as st

from utils.calculations import expected_value, implied_probability, kelly_stakes

st.title("Edge Finder")
st.write(
    "Compare a sportsbook price with your own estimate. Your estimate is your "
    "responsibility; the result is analysis, not a pick."
)

with st.container(border=True):
    odds_col, probability_col = st.columns(2)
    with odds_col:
        odds = st.number_input(
            "American odds",
            min_value=-1000,
            max_value=1000,
            value=-110,
            step=5,
            help="Enter odds such as -110 or +150. Values from -99 through +99 are invalid.",
        )
    with probability_col:
        probability_percent = st.slider(
            "Your estimated win probability",
            min_value=1,
            max_value=99,
            value=55,
            format="%d%%",
            help="Use your own research. This is not a probability generated by the app.",
        )

    stake_col, bankroll_col = st.columns(2)
    with stake_col:
        stake = st.number_input(
            "Planned stake ($)",
            min_value=0.0,
            value=25.0,
            step=5.0,
            help="The amount you are considering risking on this wager.",
        )
    with bankroll_col:
        bankroll = st.number_input(
            "Available bankroll for Kelly sizing ($)",
            min_value=0.0,
            value=500.0,
            step=50.0,
            help="A reference amount used only to translate Kelly fractions into dollars.",
        )
    st.text_area(
        "Research notes (optional)",
        placeholder="What informed your probability estimate?",
        help="Keep track of your assumptions; notes are not used in the calculation.",
    )

try:
    odds_value = int(odds)
    probability = probability_percent / 100
    market_probability = implied_probability(odds_value)
    ev = expected_value(stake, probability, odds_value)
    full_kelly, half_kelly = kelly_stakes(bankroll, probability, odds_value)
except ValueError as exc:
    st.error(str(exc))
else:
    gap = probability - market_probability
    metric_a, metric_b, metric_c = st.columns(3)
    metric_a.metric("Market implied probability", f"{market_probability:.1%}")
    metric_b.metric(
        "Your estimate vs. market",
        f"{gap:+.1%}",
        help="A positive difference means your estimate is higher than the raw market-implied probability.",
    )
    metric_c.metric("Expected value", f"${ev:+.2f}", help="Expected net profit per planned stake.")

    if ev > 0:
        st.success(
            f"**Positive EV based on your estimate:** at these inputs, the "
            f"calculated average net return is ${ev:.2f} per wager of ${stake:.2f}. "
            "This depends entirely on the accuracy of your probability estimate."
        )
    elif ev < 0:
        st.warning(
            f"**Negative EV based on your estimate:** at these inputs, the "
            f"calculated average net return is ${ev:.2f} per wager of ${stake:.2f}."
        )
    else:
        st.info("**Approximately break-even:** your inputs imply no expected net gain or loss.")

    chart = go.Figure(
        go.Bar(
            x=["Market", "Your estimate"],
            y=[market_probability * 100, probability_percent],
            marker_color=["#f6bd60", "#e87524"],
            text=[f"{market_probability:.1%}", f"{probability:.1%}"],
            textposition="outside",
        )
    )
    chart.update_layout(
        title="Win probability comparison",
        yaxis_title="Probability (%)",
        yaxis_range=[0, 100],
        showlegend=False,
        height=330,
        margin=dict(t=55, b=35, l=35, r=20),
    )
    st.plotly_chart(chart, width="stretch")

    kelly_left, kelly_right = st.columns(2)
    kelly_left.metric("Full-Kelly reference", f"${full_kelly:.2f}")
    kelly_right.metric("Half-Kelly reference", f"${half_kelly:.2f}")
    st.warning(
        "Kelly sizing is aggressive and highly sensitive to probability-estimate "
        "errors. These are mathematical references, not stake recommendations; "
        "fractional Kelly reduces but does not remove risk."
    )

st.caption(
    "The implied probability is a raw single-side conversion and does not remove "
    "the sportsbook's margin."
)
